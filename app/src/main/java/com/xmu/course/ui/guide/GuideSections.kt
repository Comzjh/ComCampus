    fun find(id: String?): GuideSection? = sections.firstOrNull { it.id == id }

    /** E2：分步教程结束后要跳去哪一章详细指南。 */
    fun sectionIdForTutorial(tutorialId: String): String?
        = sections.firstOrNull { it.relatedTutorialId == tutorialId }?.id
